// Shared by scripts/generate-catalog.mjs (writes) and
// scripts/validate-catalog.mjs (diffs), so the two can never disagree about
// what the generated catalog files should contain.
const camel = (id) => id.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());

const HEADER = '// GENERATED by scripts/generate-catalog.mjs from packages/core/src/catalog.ts.\n// Do not edit: `npm run catalog` fails when these files drift from the catalog.\n';

function definitionLiteral(definition) {
  const entries = Object.entries(definition).filter(([, value]) => value !== undefined);
  const body = entries.map(([key, value]) => {
    const property = /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
    return `${property}: ${JSON.stringify(value)}`;
  });
  return `{ ${body.join(', ')} }`;
}

function canonicalModule(definition) {
  const kindImport = `${camel(definition.kind)}Css`;
  return `${HEADER}import { baseCss } from '../css/base.js';
import { ${kindImport} } from '../css/kinds/${definition.kind}.js';
import { renderLoaderWithDefinition } from '../render.js';
import type { LoaderConfig, LoaderDefinition } from '../types.js';

const definition: LoaderDefinition = ${definitionLiteral(definition)};
const styles = \`\${baseCss}\${${kindImport}}\`;

export const ${camel(definition.id)} = (config: Omit<LoaderConfig, 'type'> = {}) =>
  renderLoaderWithDefinition({ ...config, type: definition.id }, definition, styles);
`;
}

function aliasModule(definition) {
  const target = camel(definition.aliasOf);
  return `${HEADER}// Deprecated alias of "${definition.aliasOf}": renders that design.\nimport { ${target} } from './${definition.aliasOf}.js';

export const ${camel(definition.id)} = ${target};
`;
}

/** Map of packages/core-relative path to the content that path must contain. */
export function catalogArtifacts(loaderRegistry) {
  const files = new Map();
  for (const definition of loaderRegistry) {
    files.set(`src/loaders/${definition.id}.ts`, definition.aliasOf ? aliasModule(definition) : canonicalModule(definition));
  }
  const barrel = [
    HEADER,
    ...loaderRegistry.map((d) => `export { ${camel(d.id)} } from './${d.id}.js';`),
    ''
  ].join('\n');
  files.set('src/loaders/index.ts', barrel);

  const idsFile = [
    HEADER,
    '/** Every public catalog ID, deprecated aliases included. */',
    'export const loaderIds = [',
    ...loaderRegistry.map((d) => `  ${JSON.stringify(d.id)},`),
    '] as const;',
    '',
    'export type LoaderId = (typeof loaderIds)[number];',
    ''
  ].join('\n');
  files.set('src/ids.ts', idsFile);
  return files;
}

export { camel };
