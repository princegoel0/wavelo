// Generates dist/tokens.css: the Wavelo custom properties that a page can declare
// once, globally, without changing how any design renders.
//
// The rule is mechanical rather than a judgement call. A token is emitted only when
// every `var(--wavelo-token, fallback)` in the built sheet agrees on the same
// fallback, because a `:root` declaration replaces that fallback everywhere at once.
// `--wavelo-radius`, `--wavelo-gap` and `--wavelo-ease` are therefore absent: a bar,
// a ring and a card each author a different default, and one global value would
// flatten them. `--wavelo-width` and `--wavelo-height` are absent for the same
// reason in the other direction - they fall back through `--wavelo-size`, and
// declaring them would cut that chain.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const sheetPath = resolve(root, 'packages/core/dist/wavelo.css');
const tokensPath = resolve(root, 'packages/core/dist/tokens.css');

/** Every `var()` in the sheet, as custom property name to the set of fallbacks used. */
function collect(sheet) {
  const fallbacks = new Map();
  for (let index = sheet.indexOf('var('); index !== -1; index = sheet.indexOf('var(', index + 4)) {
    let cursor = index + 4;
    while (cursor < sheet.length && /[\s]/.test(sheet[cursor])) cursor++;
    const nameMatch = /^--[a-z0-9-]+/i.exec(sheet.slice(cursor));
    if (!nameMatch) continue;
    const name = nameMatch[0];
    cursor += name.length;
    if (sheet[cursor] !== ',') continue;
    // Read to the comma's matching close paren, counting nesting: a fallback is
    // often another var().
    let depth = 1;
    let value = '';
    for (cursor++; cursor < sheet.length; cursor++) {
      const character = sheet[cursor];
      if (character === '(') depth++;
      else if (character === ')') {
        depth--;
        if (!depth) break;
      }
      value += character;
    }
    if (!fallbacks.has(name)) fallbacks.set(name, new Set());
    fallbacks.get(name).add(value.trim());
  }
  return fallbacks;
}

const sheet = await readFile(sheetPath, 'utf8');
const collected = collect(sheet);
const safe = [...collected.entries()]
  .filter(([, values]) => values.size === 1)
  .map(([name, values]) => [name, [...values][0]])
  .filter(([, value]) => !/(url\s*\(|[;"'<>\\])/.test(value))
  .sort(([a], [b]) => a.localeCompare(b));

const excluded = [...collected.keys()].filter((name) => !safe.some(([token]) => token === name)).sort();

await writeFile(
  tokensPath,
  `/*
 * Wavelo tokens, for a page that wants them declared rather than inherited.
 *
 * Generated by scripts/emit-tokens.mjs from dist/wavelo.css: a property appears here
 * only where every rule that reads it agrees on the same default, so importing this
 * sheet cannot change how any design renders. Properties with a per-design default
 * stay in the rules that read them and are listed at the bottom of this file.
 *
 * Import it, or copy it into your own :root block, and override any line.
 */
:root{
${safe.map(([name, value]) => `  ${name}: ${value};`).join('\n')}
}

/* Not declared above, because the designs do not agree on a default:
${excluded.map((name) => ` *   ${name}`).join('\n')}
 */
`,
  'utf8'
);

console.log(`dist/tokens.css: ${safe.length} tokens declared, ${excluded.length} left to the rules that read them (${excluded.join(', ') || 'none'}).`);
